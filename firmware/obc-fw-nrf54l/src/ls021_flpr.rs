//! The LS021B7DD02 display backend, driven through the FLPR coprocessor.
//!
//! The board's composition edge pairs [`Frame64`], the resident device-64 frame, with this module's
//! [`Ls021Flpr`] presenter, so no panel-specific code reaches the map plane's callers. The contract
//! impls are at the bottom of this file.
//!
//! What lives here is everything that talks to the FLPR: the cross-core [`Control`] block and its
//! dirty-row span list, which is normative with the C blob `src/flpr/flpr_scan.c` and static-asserts
//! to 96 bytes on both sides; [`launch_flpr`], which copies the blob into FLPR RAM, arms the control
//! block, releases the core and waits for its `ALIVE` stamp; and [`Ls021Flpr`] itself.
//!
//! The FLPR scans the framebuffer directly through `fb_addr`. A push publishes the span list and
//! rings one masked `CMD_RUN_FRAME`, and the FLPR packs each dirty row to the wire itself. The app
//! renders the whole frame each redraw, but the push — the dominant cost, about 44 ms full-frame —
//! scales to the changed-row span, because the FLPR fast-forwards the gate over unchanged rows and
//! stops after the last one. `Presenter::present` derives the spans from a per-row hash of the last
//! pushed frame.
//!
//! The push is async: it rings the doorbell and awaits the FLPR's EGU20 frame ack, so the scan costs
//! the M33 nothing. The wait is bounded by [`FRAME_DEADLINE`], and a timeout reads as a transport
//! fault: the caller keeps the last frame, re-arms the diff and retries. The overlay push
//! deliberately blocks ([`run_spans_blocking`](Ls021Flpr::run_spans_blocking)): its ~9 KB composite
//! and save scratch must stay stack transients, because alive across an `await` they become task
//! future state in a static and permanently shrink the residual stack.
//!
//! COM stays on the M33 and is not here. If the FLPR ever faults, COM must keep alternating so the
//! panel never takes a DC bias.
//!
//! The same coprocessor also runs the sEMMC soft peripheral, and [`crate::flpr_mux`] owns which
//! image has the hart. Two seams reach out of this module into it: every push funnels through
//! [`ring_spans`](Ls021Flpr::ring_spans), which calls
//! [`flpr_mux::ensure_display`](crate::flpr_mux::ensure_display) first, and a scan in flight must
//! never be parked ([`scan_in_flight`], [`wait_scan_settled`]), which is the one window in which
//! handing the FLPR to storage would abandon a half-drawn frame.

