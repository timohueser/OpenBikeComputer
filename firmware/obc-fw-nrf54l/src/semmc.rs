const WAIT_SLICE_CYCLES: u32 = 640;

/// SD bytes per block. Fixed: the layers above assume it and SDHC and SDXC cards cannot be told
/// otherwise.
pub const BLOCK_BYTES: usize = 512;
/// `CURRENT_STATE` in an R1: the transfer state. Anything else means a transfer must not start.
pub const CARD_STATE_TRAN: u8 = 4;
/// `CURRENT_STATE`: the card is programming (the completion signal for a write).
const CARD_STATE_PRG: u8 = 7;
/// R1 error bits, per the SD Physical Layer spec's card-status table, derived per bit rather than
/// copied, because the difference between an error and a status flag is the difference between a
/// failed read and a working one.
///
/// Deliberately excluded, for two different reasons. `CARD_ECC_DISABLED` (14), `ERASE_RESET` (13)
/// and `CARD_IS_LOCKED` (25) are status bits or a state in the spec's own classification, so
/// failing a read on them would be a bug. `AKE_SEQ_ERROR` (3) is an error bit, but this driver
/// never runs the authentication sequence it reports on, so failing every later read over a feature
/// we do not use would be the worse outcome.
const R1_ERROR_MASK: u32 = (1 << 31)  // OUT_OF_RANGE
    | (1 << 30)                       // ADDRESS_ERROR
    | (1 << 29)                       // BLOCK_LEN_ERROR
    | (1 << 28)                       // ERASE_SEQ_ERROR
    | (1 << 27)                       // ERASE_PARAM
    | (1 << 26)                       // WP_VIOLATION
    | (1 << 24)                       // LOCK_UNLOCK_FAILED
    | (1 << 23)                       // COM_CRC_ERROR
    | (1 << 22)                       // ILLEGAL_COMMAND
    | (1 << 21)                       // CARD_ECC_FAILED
    | (1 << 20)                       // CC_ERROR (internal controller error)
    | (1 << 19)                       // ERROR (generic, unknown)
    | (1 << 16)                       // CSD_OVERWRITE
    | (1 << 15); // WP_ERASE_SKIP

/// Set by [`on_vpr00_irq`]. The completion wait sleeps on this rather than spinning on the VRI, but
/// the VRI events stay the authority (see [`Semmc::wait_completion`]).
static COMPLETION: AtomicBool = AtomicBool::new(false);
/// One-shot latch so "no completion interrupt ever arrived" is diagnosed once, not per block.
static WARNED_NO_IRQ: AtomicBool = AtomicBool::new(false);

/// The `VPR00_IRQn` handler body: call this from the vector.
///
/// It is a plain function so the transfer-state mutation stays with the sEMMC driver while
/// `board.rs` owns the hardware vector binding. `main.rs` arms the NVIC line once. The VRI-side
/// gate (`INTEN`) and the VEVIF gate (`VPR00.INTENSET` bit 20) are armed by
/// [`Semmc::boot_firmware`] on every boot, because `INTENSET` writes are silently dropped while the
/// VPR core is stopped.
///
/// The latched VEVIF event must be cleared, or the level-triggered IRQ re-fires forever.
pub fn on_vpr00_irq() {
    // SAFETY: a fixed MMIO address in the VPR00 secure alias; no Rust object aliases it.
    unsafe { VPR00_EVENTS_TRIGGERED.add(EV_COMPLETION).write_volatile(0) };
    COMPLETION.store(true, Ordering::Release);
}

/// Why a storage operation failed. Every variant is returned, never panicked or hung on.
///
/// `Debug` is not decoration: `embedded_sdmmc::BlockDevice::Error` requires it. The real
/// diagnostics stay `defmt::Format`.
#[derive(Clone, Copy, PartialEq, Eq, Debug, defmt::Format)]
pub enum SemmcError {
    /// A second command tried to start while a deferred write still owned the peripheral.
    Busy,
    /// The firmware never echoed a barrier counter — it is wedged (or was never booted).
    Barrier,
    /// The image never stamped ready after a boot.
    NoBoot,
    /// No completion within the operation's deadline. The firmware has been recovered — a warm
    /// reboot and power-on — before this returns, so the next command starts from a known state.
    Timeout,
    /// The firmware raised `EVENTS_ABORTED`; the payload is its `STATUS` register
    /// (`CMDTIMEOUT` / `CMDCRCERROR` / `DATACRCERROR` / `RETRYEXCEEDED` / `PROTOCOLERR`).
    Aborted(u32),
    /// The card answered, but its R1 carries error bits.
    CardStatus(u32),
    /// The card did not leave `prg` (or reach `tran`) within the deadline.
    CardBusy,
    /// Card identification did not complete — no card, an unpowered socket, or a broken bus.
    NoCard,
    /// The card is not an SDHC or SDXC card. SDSC is byte-addressed and caps at 2 GB, and nothing
    /// this device stores fits on one, so it is rejected rather than half-supported.
    UnsupportedCard,
    /// The caller's buffer is not a whole number of 512 B blocks, is empty, or is not 32-bit
    /// aligned — the firmware's DMA requires all three.
    BadBuffer,
    /// The requested block span runs past the card's capacity.
    OutOfRange,
    /// A transfer was attempted before [`Semmc::init_card`] succeeded.
    NotInitialised,
    /// The transport's failure latch is open, so the operation was refused without touching the
    /// device. See [`crate::flpr_mux::with_storage`].
    Unhealthy,
}

impl SemmcError {
    /// Whether the device was actually attempted, which is what the transport's health latch
    /// counts. A caller-side refusal costs microseconds and says nothing about the card, so it must
    /// neither extend a failure run nor clear one.
    ///
    /// The match is exhaustive on purpose: a new variant has to be classified here or the board
    /// does not build. The refusals are `check_request`'s three, `start_write_blocks`'s deferred
    /// write, and the latch's own answer; everything else reached the bus or the soft peripheral.
    pub const fn is_transport_fault(self) -> bool {
        match self {
            SemmcError::BadBuffer
            | SemmcError::OutOfRange
            | SemmcError::NotInitialised
            | SemmcError::Busy
            | SemmcError::Unhealthy => false,
            SemmcError::Barrier
            | SemmcError::NoBoot
            | SemmcError::Timeout
            | SemmcError::Aborted(_)
            | SemmcError::CardStatus(_)
            | SemmcError::CardBusy
            | SemmcError::NoCard
            | SemmcError::UnsupportedCard => true,
        }
    }

    /// Decode an [`Aborted`](Self::Aborted) status word for the log.
    pub fn abort_reason(status: u32) -> &'static str {
        if status & STATUS_CMDTIMEOUT != 0 {
            "command timeout (card silent)"
        } else if status & STATUS_CMDCRCERROR != 0 {
            "command CRC"
        } else if status & STATUS_DATACRCERROR != 0 {
            "data CRC (clock too high for the wiring?)"
        } else if status & STATUS_RETRYEXCEEDED != 0 {
            "retries exceeded"
        } else if status & STATUS_PROTOCOLERR != 0 {
            "protocol error"
        } else {
            "unclassified"
        }
    }
}

