//! The microSD host: Nordic's sEMMC soft peripheral on the FLPR.
//!
//! The nRF54L has no SD host controller. Nordic ships one as a soft peripheral: a small
//! position-independent RISC-V image that the FLPR (the VPR00 coprocessor) executes, turning six
//! GPIOs into a 4-bit SD bus. The M33 fills in a register block, the VRI, that lives in the image's
//! own RAM carve, and pokes VPR tasks; the FLPR does the clocking, CRC and framing. Measured on
//! glass: 14.7 MB/s read (CMD18, 256 blocks, 32 MHz, 4-bit) and 8.2 MB/s write (CMD25, 21.3 MHz).
//!
//! The image is vendored at `vendor/semmc/`. Its carve is defined once in `build.rs`'s `contract`
//! module, which emits the constants included below, shrinks the M33's RAM region to match, and
//! cross-checks both against the image's own metadata header, so a blob update cannot silently
//! mis-size the carve.
//!
//! The public surface is the whole sequence and nothing below it: [`Semmc::start`] once per
//! power-on, then `enter_storage_mode` and `leave_storage_mode` per handover, and the two transfer
//! calls. Every one of them is synchronous. `start` waits in milliseconds but blocks rather than
//! yields, because awaiting it from `main` flattens the whole chain into `main`'s permanent
//! task-body poll frame. Boot, enable and card identification are private: law 1 is only a law if a
//! caller cannot boot the firmware without powering it on.
//!
//! ## The three laws (violating any one gives a silent hang)
//!
//! 1. Boot leaves the firmware INITIALIZED, not powered on. It ignores start triggers until
//!    `ENABLE = 1` is followed by an `__ASB` barrier ([`Semmc::enable`]). Skipping it gives a dead
//!    bus with no clock activity and nothing to see in the VRI.
//! 2. Every completion needs the transaction-close ack: `CONFIG.READYTOTRANSFER = 0` plus an
//!    `__ASB` ([`Semmc::close_transaction`]). Skipping it makes the first command after a boot work
//!    and the second time out, forever.
//! 3. R2 responses land LSW-first: `RESPONSE[0]` is bits 31:0 and `RESPONSE[3]` is bits 127:96.
//!    Every CID and CSD decode here is written against that order.
//!
//! ## The barrier
//!
//! Every state change is fenced by one of the soft-peripheral `__XSBx` macros: write the host
//! counter into `SPSYNC.AUX[0]`, trigger the matching VPR task (`__CSB` 17 for config, `__ASB` 18
//! for action, `__SSB` 19 for stop), then spin until the firmware echoes the counter into `AUX[1]`.
//! It takes about 2.2 µs. Start is task 16, and completion raises the VRI's
//! `EVENTS_XFERCOMPLETE` or `ABORTED` plus VEVIF event 20, which is `VPR00_IRQn` (see
//! [`on_vpr00_irq`]).
//!
//! ## The two blob warts, and the workarounds that beat them
//!
//! The image's per-index transfer table is hard-coded to eMMC semantics, and data descriptors on
//! indexes it thinks carry no data are ignored. Two SD commands fall in the gap:
//!
//! - CMD8: eMMC index 8 is `SEND_EXT_CSD`, a 512 B read, while SD's `SEND_IF_COND` is
//!   response-only, so the host wait never completes. Deliver and abort: send it, wait about 3 ms
//!   so the card's R7 reaches the wire, abandon the wait with `__SSB`, ack, continue. See
//!   [`Semmc::cmd8_deliver_abort`].
//! - CMD6: eMMC index 6 is `SWITCH`, an R1b with no data, while SD's `SWITCH_FUNC` streams a 64 B
//!   status block that is then orphaned, which leaves the card stuck in `data`. Drain read: follow
//!   it with a CMD17 at `NUMRETRIES = 0`, or the firmware's retry hunts for a second start bit
//!   forever. The card ignores the CMD17, because it is illegal in `data`, while the firmware's
//!   512 B read engine supplies exactly the clocks the orphaned block needs and lands it in our
//!   buffer, where `byte16 & 0xF == 1` is the card's own High-Speed confirmation. See
//!   [`Semmc::cmd6_high_speed`].
//!
//! Both disappear if Nordic ships a VRI data-phase override that beats the index table.
//!
//! This module never panics and never waits without a deadline, and the deadline is reachable with
//! no interrupts arriving at all, which is why [`Semmc::wait_completion`] is a bounded poll with an
//! interrupt fast path and not the `WFE` sleep it looks like it should be. Every failure is a
//! [`SemmcError`].

