// Pins. The order is Nordic's, not sequential.
/// `(P2 pin, sEMMC role)` for the six card pads.
const SD_PADS: [(usize, &str); 6] = [(0, "D3"), (1, "CLK"), (2, "D0"), (3, "D2"), (4, "D1"), (5, "CMD")];
/// The two pads time-shared with the display's B0/B1 data lines. They are the only ones the
/// display side drives, and the only ones that need an internal pull-up in storage mode: this
/// breakout carries its own resistors on CLK/D0/D2/CMD, and the production board fits external
/// pull-ups on CMD and DAT0-3 and then runs all internal pulls off.
const SHARED_PADS: [usize; 2] = [0, 4];
/// The four pads only storage uses. They are parked as inputs in display mode, where the external
/// pull-ups hold the bus in its SD idle-high state.
const CARD_ONLY_PADS: [usize; 4] = [1, 2, 3, 5];

// Clocks. Legal values are 128 MHz over an even divisor of 4 or more.
/// SD card-identification clock, at divisor 320.
const CLK_INIT_HZ: u32 = 400_000;
/// Default Speed data clock: what the card runs at before the High-Speed switch, and the write
/// clock afterwards.
const CLK_DS_HZ: u32 = 21_333_333;
/// High Speed read clock, after CMD6.
const CLK_HS_HZ: u32 = 32_000_000;
/// Writes cap at 21.3 MHz. 32 MHz writes fail card-side CRC on the jumper harness, which is a
/// clean failure that programs nothing, while 32 MHz reads are spotless. The clock is
/// per-transaction config, so a mixed rate is free.
const CLK_WRITE_MAX_HZ: u32 = CLK_DS_HZ;

/// Retries the firmware makes per transaction. Zero only for the CMD6 drain read, where a retry
