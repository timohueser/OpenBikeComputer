    /// The synthetic trees above write headers by hand, so this test checks the reader
    /// side against a real packed map: the committed simulator fixtures.
    #[test]
    fn reads_the_header_of_a_real_packed_map() {
        let monaco = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../apps/obc-sim/assets/monaco.obcm");
        let header = read_obcm_header(&monaco).expect("monaco.obcm header");
        assert_eq!(header.version, OBCM_VERSION, "the committed fixture is packed at the current OBCM version");
        // Monaco: repack.sh cuts it at 7.39,43.71 → 7.47,43.77; the packed coverage box
        // is a little wider (complete ways + coastline), which is exactly why the
        // manifest reports the header box and never feeds it back as an extract box.
        assert!(header.bbox.min_lat > 43_000_000 && header.bbox.max_lat < 44_000_000, "{:?}", header.bbox);
        assert!(header.bbox.min_lon > 7_000_000 && header.bbox.max_lon < 8_000_000, "{:?}", header.bbox);

        let (bytes, sha) = hash_file(&monaco).expect("hash");
        assert_eq!(bytes, fs::metadata(&monaco).unwrap().len());
        assert_eq!(sha.len(), 64);
    }

