/// Directory entries in a stable order. `read_dir` order is filesystem-dependent, so
/// sorting here is what makes the whole generator reproducible.
fn sorted_entries(dir: &Path) -> Result<Vec<PathBuf>, String> {
    let mut paths = Vec::new();
    for entry in fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))? {
        paths.push(entry.map_err(|e| format!("{}: {e}", dir.display()))?.path());
    }
    paths.sort();
    Ok(paths)
}

fn file_name(path: &Path) -> Result<String, String> {
    path.file_name()
        .and_then(|n| n.to_str())
        .map(str::to_string)
        .ok_or_else(|| format!("{}: non-UTF-8 filename", path.display()))
}

/// Region path segments and preset ids share one lowercase-kebab vocabulary: they end
/// up in URLs and in the site's region join, so `Switzerland/` and `switzerland/` must
/// not be able to coexist.
fn validate_id(id: &str) -> Result<(), String> {
    if id.is_empty() {
        return Err("`` is empty".to_string());
    }
    let ok = id
        .split('-')
        .all(|part| !part.is_empty() && part.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit()));
    if !ok {
        return Err(format!("`{id}` must be lowercase kebab-case (a-z, 0-9, single hyphens)"));
    }
    Ok(())
}

fn rel_url_path(rel: &Path) -> Result<String, String> {
    let mut parts = Vec::new();
    for c in rel.components() {
        match c {
            std::path::Component::Normal(s) => {
                parts.push(s.to_str().ok_or_else(|| format!("{}: non-UTF-8 path", rel.display()))?)
            }
            _ => return Err(format!("{}: unexpected path component", rel.display())),
        }
    }
    Ok(parts.join("/"))
}

/// The publish location. Kept deliberately narrow: anything a browser cannot resolve
/// against the catalog's own origin is a mistake worth catching at bake time.
fn normalize_base_url(base: &str) -> Result<String, String> {
    let trimmed = base.trim_end_matches('/');
    if trimmed.is_empty() {
        return Err("base URL is empty".to_string());
    }
    let absolute = trimmed.starts_with("https://") || trimmed.starts_with("http://");
    if !absolute && !trimmed.starts_with('/') {
        return Err(format!("base URL `{base}` must be absolute (`https://…`) or root-relative (`/…`)"));
    }
    if trimmed.chars().any(char::is_whitespace) {
        return Err(format!("base URL `{base}` contains whitespace"));
    }
    Ok(trimmed.to_string())
}

// --- timestamps --------------------------------------------------------------------------
//
// One strict spelling, `YYYY-MM-DDTHH:MM:SSZ`: no offsets, no fractional seconds, no
// lowercase `z`. A catalog's timestamps are compared and sorted by consumers in three
// languages; one spelling makes string comparison correct, and rejecting the rest at
// bake time is cheaper than discovering the variants later.

/// Validate `YYYY-MM-DDTHH:MM:SSZ` and return the instant as a Unix timestamp.
pub fn validate_timestamp(s: &str) -> Result<i64, String> {
    let bytes = s.as_bytes();
    if bytes.len() != 20 || bytes[10] != b'T' || bytes[19] != b'Z' {
        return Err(format!("`{s}` is not an RFC 3339 UTC instant (YYYY-MM-DDTHH:MM:SSZ)"));
    }
    let days = civil_days(&s[..10]).map_err(|e| format!("`{s}`: {e}"))?;
    let (h, m, sec) = (num(&s[11..13])?, num(&s[14..16])?, num(&s[17..19])?);
    if s.as_bytes()[13] != b':' || s.as_bytes()[16] != b':' {
        return Err(format!("`{s}` is not an RFC 3339 UTC instant (YYYY-MM-DDTHH:MM:SSZ)"));
    }
    // 60 would be a leap second; the format has no room for one and no consumer wants it.
    if h > 23 || m > 59 || sec > 59 {
        return Err(format!("`{s}` has an out-of-range time"));
    }
    Ok(days * 86_400 + i64::from(h) * 3_600 + i64::from(m) * 60 + i64::from(sec))
}

/// Validate `YYYY-MM-DD` (the Geofabrik extract date).
pub fn validate_date(s: &str) -> Result<(), String> {
    if s.len() != 10 {
        return Err(format!("`{s}` is not a YYYY-MM-DD date"));
    }
    civil_days(s).map(|_| ()).map_err(|e| format!("`{s}`: {e}"))
}

/// Format a Unix timestamp as `YYYY-MM-DDTHH:MM:SSZ`.
///
/// Hand-rolled rather than pulling a date crate in for one call site: the packer's
/// only use of civil time is stamping `generated_at`.
pub fn format_timestamp(unix: i64) -> String {
    let days = unix.div_euclid(86_400);
    let secs = unix.rem_euclid(86_400);
    let (y, m, d) = civil_from_days(days);
    format!("{y:04}-{m:02}-{d:02}T{:02}:{:02}:{:02}Z", secs / 3600, (secs % 3600) / 60, secs % 60)
}

/// `generated_at` for a run with no explicit `--generated-at`. The single place this
/// crate reads a wall clock.
pub fn now_timestamp() -> String {
    let secs = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map_or(0, |d| d.as_secs() as i64);
    format_timestamp(secs)
}

fn num(s: &str) -> Result<u32, String> {
    s.parse::<u32>().map_err(|_| format!("`{s}` is not a number"))
}

/// Days since 1970-01-01 for a validated `YYYY-MM-DD`, rejecting impossible dates
/// (2026-02-30 parses digit-wise but is not a day).
fn civil_days(date: &str) -> Result<i64, String> {
    let b = date.as_bytes();
    if b.len() != 10 || b[4] != b'-' || b[7] != b'-' {
        return Err("not a YYYY-MM-DD date".to_string());
    }
    let (y, m, d) = (num(&date[..4])? as i64, num(&date[5..7])?, num(&date[8..10])?);
    if !(1..=12).contains(&m) || d < 1 || d > days_in_month(y, m) {
        return Err("is not a real calendar date".to_string());
    }
    Ok(days_from_civil(y, m, d))
}

fn is_leap(y: i64) -> bool {
    (y % 4 == 0 && y % 100 != 0) || y % 400 == 0
}

fn days_in_month(y: i64, m: u32) -> u32 {
    match m {
        1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
        4 | 6 | 9 | 11 => 30,
        2 if is_leap(y) => 29,
        2 => 28,
        _ => 0,
    }
}

/// Howard Hinnant's `days_from_civil`: the proleptic Gregorian day number, shifted so
/// 1970-01-01 is day 0.
fn days_from_civil(y: i64, m: u32, d: u32) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = y - era * 400;
    let mp = i64::from((m + 9) % 12);
    let doy = (153 * mp + 2) / 5 + i64::from(d) - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

/// Inverse of [`days_from_civil`].
fn civil_from_days(days: i64) -> (i64, u32, u32) {
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (if m <= 2 { y + 1 } else { y }, m, d)
}

