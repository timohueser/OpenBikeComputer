/// Generate the manifest's JSON Schema from the same serde model the generator writes
/// and consumers deserialize, then add the constraints Rust types cannot express
/// (hex/timestamp patterns, coordinate ranges, the pinned envelope version).
pub fn catalog_schema() -> Value {
    let mut schema = serde_json::to_value(schemars::schema_for!(CatalogManifest)).expect("catalog schema serializes");
    let root = schema.as_object_mut().expect("root schema is an object");
    root.insert("$schema".into(), Value::String("https://json-schema.org/draft/2020-12/schema".into()));
    root.insert("title".into(), Value::String("OpenBikeComputer map catalog".into()));
    root.insert("description".into(), Value::String(CATALOG_DESCRIPTION.into()));

    let props = root.get_mut("properties").and_then(Value::as_object_mut).expect("catalog properties");
    // A consumer validating against this schema is validating against *its* envelope
    // version; a future v2 manifest must fail here rather than half-parse.
    props["schema_version"]["const"] = Value::from(CATALOG_SCHEMA_VERSION);
    props["generated_at"]["pattern"] = Value::from(TIMESTAMP_PATTERN);

    let defs = root.get_mut("$defs").and_then(Value::as_object_mut).expect("catalog definitions");
    let artifact = defs["ArtifactEntry"]["properties"].as_object_mut().expect("artifact properties");
    artifact["region_id"]["pattern"] = Value::from(REGION_ID_PATTERN);
    artifact["preset_id"]["pattern"] = Value::from(ID_PATTERN);
    artifact["sha256"]["pattern"] = Value::from("^[0-9a-f]{64}$");
    artifact["built_at"]["pattern"] = Value::from(TIMESTAMP_PATTERN);
    artifact["source_snapshot"]["pattern"] = Value::from(DATE_PATTERN);
    artifact["url"]["pattern"] = Value::from("^(https?://|/)");
    artifact["region_name"]["minLength"] = Value::from(1);

    let preset = defs["PresetEntry"]["properties"].as_object_mut().expect("preset properties");
    preset["id"]["pattern"] = Value::from(ID_PATTERN);
    preset["name"]["minLength"] = Value::from(1);
    preset["description"]["minLength"] = Value::from(1);

    // The struct's rustdoc argues the header-bbox decision at length for a reader of
    // the code; the schema wants the one-sentence contract.
    defs["CoverageBBox"]["description"] = Value::from(BBOX_DESCRIPTION);
    let bbox = defs["CoverageBBox"]["properties"].as_object_mut().expect("bbox properties");
    for f in ["min_lat", "max_lat"] {
        bound(bbox, f, -90_000_000, 90_000_000);
    }
    for f in ["min_lon", "max_lon"] {
        bound(bbox, f, -180_000_000, 180_000_000);
    }

    flatten_descriptions(&mut schema);
    schema
}

/// Doc comments arrive with the source's hard line wraps baked in. The schema is a
/// published artifact a JSON-Schema-aware editor renders, so collapse each description
/// to one line.
fn flatten_descriptions(value: &mut Value) {
    match value {
        Value::Object(map) => {
            if let Some(Value::String(d)) = map.get_mut("description") {
                *d = d.split_whitespace().collect::<Vec<_>>().join(" ");
            }
            for (_, v) in map.iter_mut() {
                flatten_descriptions(v);
            }
        }
        Value::Array(items) => items.iter_mut().for_each(flatten_descriptions),
        _ => {}
    }
}

fn bound(props: &mut Map<String, Value>, field: &str, min: i64, max: i64) {
    props[field]["minimum"] = Value::from(min);
    props[field]["maximum"] = Value::from(max);
}

/// Stable pretty representation used to regenerate the checked-in schema:
/// `obc-pack schema --catalog > obc-pack/schema/catalog.schema.json`.
pub fn catalog_schema_json() -> String {
    let mut text = serde_json::to_string_pretty(&catalog_schema()).expect("catalog schema serializes");
    text.push('\n');
    text
}

