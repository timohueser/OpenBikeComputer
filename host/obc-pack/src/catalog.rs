//! `catalog.rs` — the **map catalog manifest**: the contract between the bakery
//! (which builds `.obcm` artifacts once, centrally) and every consumer that hands
//! one to a device (the hosted site, the desktop app). The repo-root `OBCC_Spec.md`
//! is the normative document; this module is its code authority and only producer.
//!
//! Two properties drive every design decision here.
//!
//! **The version law.** An OBCM format bump invalidates every baked artifact, so
//! `obcm_version` is read out of the artifact's own 40-byte header — never from
//! the builder's intent — and the generator refuses to emit a manifest that mixes
//! versions or carries a version this packer does not write. That makes a stale
//! bake a build failure instead of a map a rider's device silently cannot open.
//!
//! **Never partially consumed.** The manifest is written temp-then-`rename`, so a
//! reader either sees the whole previous file or the whole new one, and it is a
//! single self-delimiting JSON document, so a truncated body cannot parse. Both
//! halves are required; see [`write_atomic`] and `OBCC_Spec.md` §7.

use std::collections::BTreeMap;
use std::fs::{self, File};
use std::io::{Read, Write};
use std::path::{Path, PathBuf};

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};
use sha2::{Digest, Sha256};

use obc_formats::io::rd_i32;
use obc_formats::obcm::{HEADER_LEN, MAGIC, VERSION as OBCM_VERSION};

/// Version of the manifest envelope itself. Bump only on a breaking change to the
/// document shape — adding an optional field is not one. A consumer that does not
/// recognise this number MUST reject the whole document (`OBCC_Spec.md` §7).
pub const CATALOG_SCHEMA_VERSION: u32 = 1;

/// The generated manifest schema, checked in so the hosted site can validate a
/// fetched catalog without a Rust toolchain. A pinning test keeps it identical to
/// [`catalog_schema`] — same mechanism as `schema/config.schema.json`.
pub const CATALOG_SCHEMA_JSON: &str = include_str!("../schema/catalog.schema.json");

/// A generated manifest over the checked-in synthetic bake tree, regenerated by
/// the tests. Its `obcm_version` fields are what make the stale-generation guard
/// concrete: an OBCM bump changes this file, so it cannot go unnoticed.
pub const CATALOG_EXAMPLE_JSON: &str = include_str!("../schema/catalog.example.json");

/// The OBCM format version this catalog surface was written and pinned against.
///
/// Deliberately a literal, not an alias for [`OBCM_VERSION`]: moving OBCM's version
/// constant must *break* a test, because the bump invalidates every artifact already
/// baked and published. See the `obcm_version_pin_is_deliberate` test for the
/// checklist that failure prints.
pub const PINNED_OBCM_VERSION: u8 = 10;

/// Default manifest filename inside a bake tree.
pub const DEFAULT_MANIFEST_NAME: &str = "catalog.json";

const REGIONS_DIR: &str = "regions";
const PRESETS_DIR: &str = "presets";
const ARTIFACT_EXT: &str = ".obcm";
const SIDECAR_EXT: &str = ".obcm.json";

/// Hash/copy buffer. Artifacts are hundreds of megabytes, so the file is streamed;
/// nothing in this module ever holds an artifact body in memory.
const HASH_BUF: usize = 64 * 1024;

// --- the manifest ------------------------------------------------------------------------

/// The catalog manifest: every artifact the bakery published, plus the presets they
/// were built with.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CatalogManifest {
    /// Manifest envelope version. A consumer that does not recognise it rejects the
    /// entire document rather than reading the fields it happens to understand.
    pub schema_version: u32,
    /// When this manifest was generated, RFC 3339 UTC (`YYYY-MM-DDTHH:MM:SSZ`).
    pub generated_at: String,
    /// The presets artifacts were built with, sorted by `id`. Display order is the
    /// consumer's business, not the manifest's.
    pub presets: Vec<PresetEntry>,
    /// Every published artifact, sorted by `(region_id, preset_id)`.
    pub artifacts: Vec<ArtifactEntry>,
}

/// One style preset offered to the user.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct PresetEntry {
    /// Stable preset id, e.g. `default`. Matches `preset_id` on artifacts.
    pub id: String,
    /// Display name, e.g. `Bikepacking`.
    pub name: String,
    /// One-line description of what this preset draws.
    pub description: String,
    /// Preset content version — bumped whenever the preset's styling changes, so a
    /// consumer can tell "same preset, restyled" from "same bytes".
    pub version: u32,
    /// Optional reference to a rendered preview asset, resolved against the same
    /// base URL as `url` on artifacts. Absent until the preview exists.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub preview: Option<String>,
}

/// One published `.obcm` artifact: a (region, preset) pair.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct ArtifactEntry {
    /// Slash-separated region id mirroring the Geofabrik hierarchy, e.g.
    /// `europe/switzerland`. Derived from the artifact's directory path.
    pub region_id: String,
    /// Human-readable region name, e.g. `Switzerland`.
    pub region_name: String,
    /// The preset this artifact was built with; matches a `presets[].id`.
    pub preset_id: String,
    /// The preset's `version` **as recorded by the bake job that produced this
    /// artifact** — read from its sidecar, not from the preset config sitting in the
    /// tree when the manifest was generated.
    ///
    /// That distinction is the whole point of the field. A preset restyle invalidates
    /// only that preset's artifacts, so partial re-bakes are the normal operation (a
    /// full bake is ~20 CPU-hours). Copied from the current preset config it would
    /// equal `presets[].version` by construction and could never signal anything,
    /// while every not-yet-re-baked artifact silently claimed styling it does not
    /// have. Lower than the matching `presets[].version` means exactly one thing: this
    /// artifact carries older styling (`OBCC_Spec.md` §3).
    pub preset_version: u32,
    /// OBCM format version, read from the artifact's own header — never from the
    /// builder's intent. A consumer MUST refuse an artifact whose version the target
    /// firmware cannot read (`OBCC_Spec.md` §6).
    pub obcm_version: u8,
    /// Artifact size in bytes.
    pub bytes: u64,
    /// Lowercase hex SHA-256 of the artifact bytes.
    pub sha256: String,
    /// Coverage bbox, copied from the artifact header. Descriptive output, never a
    /// build input — see [`CoverageBBox`].
    pub bbox: CoverageBBox,
    /// When the artifact was packed, RFC 3339 UTC.
    pub built_at: String,
    /// Date of the OSM extract it was packed from, `YYYY-MM-DD`.
    pub source_snapshot: String,
    /// Absolute or root-relative URL the artifact can be fetched from.
    pub url: String,
}

/// The artifact's coverage bounding box in **microdegrees**, exactly as the OBCM
/// header stores it.
///
/// This is what the packed file actually covers, which is always a little wider than
/// the extract box it was cut from: complete ways and stray coastline features push
/// it out. `obc-sim/assets/repack.sh` therefore forbids feeding a header bbox back in
/// as an extract bbox — self-sourcing ratchets the box wider on every re-pack (a
/// fixture once grew to 14.5 MB that way).
///
/// That rule is about *inputs*. This field is an *output*: the honest answer to "what
/// does this download cover?", which is the only question a catalog consumer asks. It
/// MUST NOT be used as a packer input bbox, and `OBCC_Spec.md` §4 says so normatively.
///
/// Microdegrees rather than degrees, because the format's own unit is integer
/// microdegrees and integers serialize deterministically; floats would not.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CoverageBBox {
    pub min_lat: i32,
    pub min_lon: i32,
    pub max_lat: i32,
    pub max_lon: i32,
}

/// A generated manifest plus non-fatal observations about the tree.
///
/// Warnings are returned rather than printed: the bakery decides whether a coverage
/// hole is a log line or a failed job, and tests can assert on them.
#[derive(Debug, Clone)]
pub struct GeneratedCatalog {
    pub manifest: CatalogManifest,
    pub warnings: Vec<String>,
}

/// Generator inputs that cannot be derived from the tree.
#[derive(Debug, Clone)]
pub struct CatalogOptions {
    /// Prefix every artifact `url` is built from — the location the tree is published
    /// at. Absolute `http(s)://…` or root-relative `/…`; a trailing slash is trimmed.
    pub base_url: String,
    /// The manifest's `generated_at`, RFC 3339 UTC.
    ///
    /// Passed in, not read from the clock, so the generator is a pure function of
    /// (tree, options): the same tree yields byte-identical output. The CLI fills this
    /// from the system clock when `--generated-at` is absent, and that is the *only*
    /// place a wall clock enters the manifest — `built_at` comes from the sidecars.
    pub generated_at: String,
}

// --- generation --------------------------------------------------------------------------

/// Walk a bake output tree and build the manifest.
///
/// The tree is self-describing (`OBCC_Spec.md` §8):
///
/// ```text
/// <tree>/presets/<preset_id>.json              the exact packer config used, `_meta` describes it
/// <tree>/regions/<a>/<b>/<preset_id>.obcm      the artifact; its directory path is the region id
/// <tree>/regions/<a>/<b>/<preset_id>.obcm.json its sidecar (region name, snapshot, build time)
/// ```
///
/// Per-artifact sidecars rather than one central index: a matrix bake runs one job per
/// (region, preset), and each job writes only its own two files. Nothing has to be
/// merged, so nothing can race.
pub fn generate(tree: &Path, opts: &CatalogOptions) -> Result<GeneratedCatalog, String> {
    let base_url = normalize_base_url(&opts.base_url)?;
    validate_timestamp(&opts.generated_at).map_err(|e| format!("generated_at: {e}"))?;

    let presets = read_presets(&tree.join(PRESETS_DIR))?;
    let regions_root = tree.join(REGIONS_DIR);
    if !regions_root.is_dir() {
        return Err(format!("{}: no `{REGIONS_DIR}/` directory — is this a bake tree?", tree.display()));
    }

    let mut artifacts = Vec::new();
    collect_region_dirs(&regions_root, &mut Vec::new(), &mut |region_id, dir| {
        read_region(region_id, dir, tree, &presets, &base_url, &mut artifacts)
    })?;

    if artifacts.is_empty() {
        return Err(format!("{}: no `.obcm` artifacts found — refusing to publish an empty catalog", tree.display()));
    }

    // Sorted output, so the manifest depends on the tree's content and not on the
    // order the filesystem happened to hand back directory entries.
    artifacts.sort_by(|a, b| (&a.region_id, &a.preset_id).cmp(&(&b.region_id, &b.preset_id)));

    let warnings = check_coherence(&artifacts, &presets)?;

    let manifest = CatalogManifest {
        schema_version: CATALOG_SCHEMA_VERSION,
        generated_at: opts.generated_at.clone(),
        presets: presets.into_values().collect(),
        artifacts,
    };
    Ok(GeneratedCatalog { manifest, warnings })
}

/// Stable serialization: pretty-printed with a trailing newline, so a published
/// manifest diffs line-by-line and `generate` → `manifest_json` is byte-reproducible.
///
/// Field order is struct-declaration order — `serde_json`'s `preserve_order` feature
/// (already mandatory for the packer's config) keeps maps insertion-ordered too.
pub fn manifest_json(manifest: &CatalogManifest) -> String {
    let mut text = serde_json::to_string_pretty(manifest).expect("manifest serializes");
    text.push('\n');
    text
}

/// Write the manifest so it is never observed half-written.
///
/// Temp file in the *same directory* (so the rename cannot cross a filesystem) →
/// `sync_all` → `rename`, which is atomic on every filesystem the bakery runs on. A
/// concurrent reader therefore sees either the complete previous manifest or the
/// complete new one, never a prefix of either.
///
/// That covers the local tree. The other half of "never partially consumed" is the
/// consumer's, and it is not optional: a catalog client MUST read the entire response
/// body, parse it as one JSON document, and check `schema_version` *before* using any
/// field. A single self-delimiting document is what makes that check sufficient —
/// truncation cannot survive `JSON.parse`. `OBCC_Spec.md` §7 states both halves.
pub fn write_atomic(path: &Path, manifest: &CatalogManifest) -> Result<(), String> {
    let body = manifest_json(manifest);
    let dir = path.parent().filter(|p| !p.as_os_str().is_empty()).map_or_else(|| PathBuf::from("."), Path::to_path_buf);
    // Unique per process so two generators pointed at one tree cannot corrupt each
    // other's temp file; the rename still makes the last writer win cleanly.
    let tmp = dir.join(format!(
        ".{}.tmp{}",
        path.file_name().and_then(|n| n.to_str()).unwrap_or(DEFAULT_MANIFEST_NAME),
        std::process::id()
    ));

    let write = |tmp: &Path| -> std::io::Result<()> {
        let mut f = File::create(tmp)?;
        f.write_all(body.as_bytes())?;
        // Durability before visibility: a crash between rename and writeback must not
        // leave a zero-length file where a valid manifest used to be.
        f.sync_all()
    };
    if let Err(e) = write(&tmp) {
        let _ = fs::remove_file(&tmp);
        return Err(format!("{}: {e}", tmp.display()));
    }
    if let Err(e) = fs::rename(&tmp, path) {
        let _ = fs::remove_file(&tmp);
        return Err(format!("{} -> {}: {e}", tmp.display(), path.display()));
    }
    // Best effort: persist the directory entry itself. Not portable (opening a
    // directory fails on Windows), and the rename is already atomic, so a failure
    // here is not worth aborting a good publish for.
    if let Ok(d) = File::open(&dir) {
        let _ = d.sync_all();
    }
    Ok(())
}

// --- tree walking ------------------------------------------------------------------------

/// Recurse `regions/`, calling `visit` for every directory that holds artifacts.
///
/// A directory may both hold artifacts and contain sub-regions: `regions/europe/germany`
/// can be baked while `regions/europe/germany/bayern` is baked separately, which is
/// exactly the nested-region case the region picker has to render.
fn collect_region_dirs(
    dir: &Path,
    segments: &mut Vec<String>,
    visit: &mut impl FnMut(&str, &Path) -> Result<(), String>,
) -> Result<(), String> {
    let mut subdirs = Vec::new();
    let mut has_artifacts = false;
    for entry in sorted_entries(dir)? {
        let name = file_name(&entry)?;
        // Dotfiles are tooling debris (`.DS_Store`, `.gitkeep`), never catalog content.
        if name.starts_with('.') {
            continue;
        }
        if entry.is_dir() {
            validate_id(&name).map_err(|e| format!("{}: region path segment {e}", entry.display()))?;
            subdirs.push((name, entry));
        } else if name.ends_with(SIDECAR_EXT) {
            // Paired with its artifact below; a stray sidecar is caught in read_region.
        } else if name.ends_with(ARTIFACT_EXT) {
            has_artifacts = true;
        } else {
            // Silence here would let a mis-named artifact read as "region not covered",
            // which is indistinguishable from a deliberate curation choice.
            return Err(format!("{}: unexpected entry in a region tree (expected `*{ARTIFACT_EXT}`, `*{SIDECAR_EXT}`, or a sub-region directory)", entry.display()));
        }
    }

    if has_artifacts {
        if segments.is_empty() {
            return Err(format!("{}: artifacts must live in a region directory under `{REGIONS_DIR}/`", dir.display()));
        }
        visit(&segments.join("/"), dir)?;
    }
    for (name, path) in subdirs {
        segments.push(name);
        collect_region_dirs(&path, segments, visit)?;
        segments.pop();
    }
    Ok(())
}

/// Turn one region directory into artifact entries.
fn read_region(
    region_id: &str,
    dir: &Path,
    tree: &Path,
    presets: &BTreeMap<String, PresetEntry>,
    base_url: &str,
    out: &mut Vec<ArtifactEntry>,
) -> Result<(), String> {
    let mut region_name: Option<(String, PathBuf)> = None;
    let mut sidecars = Vec::new();
    let mut artifacts = Vec::new();
    for entry in sorted_entries(dir)? {
        let name = file_name(&entry)?;
        if name.starts_with('.') || entry.is_dir() {
            continue;
        }
        if let Some(stem) = name.strip_suffix(SIDECAR_EXT) {
            sidecars.push(stem.to_string());
        } else if let Some(stem) = name.strip_suffix(ARTIFACT_EXT) {
            artifacts.push((stem.to_string(), entry));
        }
    }

    for (preset_id, path) in artifacts {
        validate_id(&preset_id).map_err(|e| format!("{}: preset id {e}", path.display()))?;
        if !presets.contains_key(&preset_id) {
            return Err(format!(
                "{}: preset `{preset_id}` is not described in `{PRESETS_DIR}/{preset_id}.json` — the tree must \
                 describe every preset it holds artifacts for",
                path.display()
            ));
        }
        let sidecar_path = path.with_file_name(format!("{preset_id}{SIDECAR_EXT}"));
        let sidecar = read_sidecar(&sidecar_path)?;
        sidecars.retain(|s| s != &preset_id);

        let header = read_obcm_header(&path)?;
        // The version law, enforced at the earliest point the answer is known and
        // against *this packer's* version rather than merely "all the same" — a
        // catalog baked entirely with last month's packer is the failure mode this
        // check exists for, and it is uniform.
        if header.version != OBCM_VERSION {
            return Err(format!(
                "{}: artifact is OBCM v{} but this obc-pack writes v{OBCM_VERSION}. An OBCM format bump invalidates \
                 every baked artifact (OBCC_Spec.md §6) — re-bake this region with the current packer. Publishing a \
                 mixed-version catalog would hand devices maps they cannot open.",
                path.display(),
                header.version
            ));
        }
        let (bytes, sha256) = hash_file(&path)?;

        // Region names come from independently-written sidecars; a disagreement means
        // two jobs disagreed about what they were baking. Fail rather than pick one.
        match &region_name {
            None => region_name = Some((sidecar.region_name.clone(), sidecar_path.clone())),
            Some((first, first_path)) if first != &sidecar.region_name => {
                return Err(format!(
                    "region `{region_id}`: conflicting region_name — `{first}` in {} but `{}` in {}",
                    first_path.display(),
                    sidecar.region_name,
                    sidecar_path.display()
                ));
            }
            Some(_) => {}
        }

        let rel =
            path.strip_prefix(tree).map_err(|_| format!("{}: artifact is outside the tree root", path.display()))?;
        let url = format!("{base_url}/{}", rel_url_path(rel)?);

        out.push(ArtifactEntry {
            region_id: region_id.to_string(),
            region_name: sidecar.region_name,
            preset_id,
            preset_version: sidecar.preset_version,
            obcm_version: header.version,
            bytes,
            sha256,
            bbox: header.bbox,
            built_at: sidecar.built_at,
            source_snapshot: sidecar.source_snapshot,
            url,
        });
    }

    if let Some(orphan) = sidecars.first() {
        return Err(format!(
            "{}: sidecar with no artifact — `{orphan}{ARTIFACT_EXT}` is missing",
            dir.join(format!("{orphan}{SIDECAR_EXT}")).display()
        ));
    }
    Ok(())
}

/// The facts a bake job knows that the artifact bytes cannot state.
///
/// Every field here is a *record of the bake*, fixed when the artifact was written.
/// Nothing in this struct may be re-derived at generation time from the tree's current
/// state — that is what lets the manifest describe an artifact the tree has since
/// moved past.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct ArtifactSidecar {
    region_name: String,
    /// The `_meta.version` of the preset config this artifact was actually packed
    /// with. Recorded here rather than read back off the tree's preset config, which
    /// the next restyle moves out from under already-baked artifacts.
    preset_version: u32,
    /// RFC 3339 UTC instant the artifact was packed.
    built_at: String,
    /// `YYYY-MM-DD` date of the Geofabrik extract it was packed from.
    source_snapshot: String,
}

fn read_sidecar(path: &Path) -> Result<ArtifactSidecar, String> {
    let text = fs::read_to_string(path).map_err(|e| {
        format!(
            "{}: {e} — every artifact needs a sidecar (region_name, preset_version, built_at, source_snapshot)",
            path.display()
        )
    })?;
    let sidecar: ArtifactSidecar = serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
    if sidecar.region_name.trim().is_empty() {
        return Err(format!("{}: region_name is empty", path.display()));
    }
    validate_timestamp(&sidecar.built_at).map_err(|e| format!("{}: built_at {e}", path.display()))?;
    validate_date(&sidecar.source_snapshot).map_err(|e| format!("{}: source_snapshot {e}", path.display()))?;
    Ok(sidecar)
}

/// `_meta` from a packer preset config. The preset file in the tree is the **current**
/// definition of a preset: it names and describes it, and its `version` is what a fresh
/// bake would produce. What an already-baked artifact was built with is its sidecar's
/// business, not this file's.
#[derive(Debug, Deserialize)]
struct PresetDoc {
    #[serde(rename = "_meta")]
    meta: Option<PresetMeta>,
}

#[derive(Debug, Deserialize)]
struct PresetMeta {
    id: String,
    name: String,
    description: String,
    version: u32,
    /// Filled in once a rendered preview asset exists; other `_meta` keys the web
    /// builder uses (`swatch`, `palette_note`) are deliberately not in the catalog.
    #[serde(default)]
    preview: Option<String>,
}

fn read_presets(dir: &Path) -> Result<BTreeMap<String, PresetEntry>, String> {
    if !dir.is_dir() {
        return Err(format!(
            "{}: no `{PRESETS_DIR}/` directory — the bake tree must describe every preset it holds artifacts for",
            dir.display()
        ));
    }
    let mut presets = BTreeMap::new();
    for path in sorted_entries(dir)? {
        let name = file_name(&path)?;
        if name.starts_with('.') || path.is_dir() {
            continue;
        }
        let Some(stem) = name.strip_suffix(".json") else {
            return Err(format!(
                "{}: only `<preset_id>.json` preset configs belong in `{PRESETS_DIR}/`",
                path.display()
            ));
        };
        validate_id(stem).map_err(|e| format!("{}: preset id {e}", path.display()))?;
        let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let doc: PresetDoc = serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        let meta = doc.meta.ok_or_else(|| {
            format!("{}: preset config has no `_meta` block (id, name, description, version)", path.display())
        })?;
        if meta.id != stem {
            return Err(format!("{}: `_meta.id` is `{}` but the filename says `{stem}`", path.display(), meta.id));
        }
        if meta.name.trim().is_empty() || meta.description.trim().is_empty() {
            return Err(format!("{}: `_meta.name` and `_meta.description` must be non-empty", path.display()));
        }
        presets.insert(
            stem.to_string(),
            PresetEntry {
                id: meta.id,
                name: meta.name,
                description: meta.description,
                version: meta.version,
                preview: meta.preview,
            },
        );
    }
    if presets.is_empty() {
        return Err(format!("{}: no preset configs found", dir.display()));
    }
    Ok(presets)
}

/// Cross-artifact rules. Everything fatal here would otherwise ship a catalog a
/// device cannot use; everything merely surprising comes back as a warning.
fn check_coherence(
    artifacts: &[ArtifactEntry],
    presets: &BTreeMap<String, PresetEntry>,
) -> Result<Vec<String>, String> {
    // A preset nobody built is a preset the picker would offer and then fail to serve.
    let mut used: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for a in artifacts {
        used.entry(a.preset_id.as_str()).or_default().push(a.region_id.as_str());
    }
    for id in presets.keys() {
        if !used.contains_key(id.as_str()) {
            return Err(format!(
                "preset `{id}` is described in `{PRESETS_DIR}/` but no artifact uses it — either bake it or drop the \
                 preset; a catalog must not advertise a preset it cannot serve"
            ));
        }
    }

    let mut warnings = Vec::new();

    // Artifact vs. the tree's current preset config. Now that `preset_version` records
    // the bake instead of mirroring the tree, the two can disagree — and each direction
    // means something different.
    for a in artifacts {
        // `read_region` already refused an artifact whose preset is undescribed.
        let Some(current) = presets.get(a.preset_id.as_str()) else { continue };
        match a.preset_version.cmp(&current.version) {
            // Artifact newer than the config that supposedly describes it: the tree is
            // internally inconsistent (a reverted preset, or one copied in from the
            // wrong place), and the catalog cannot describe that artifact honestly.
            std::cmp::Ordering::Greater => {
                return Err(format!(
                    "region `{}` preset `{}`: the artifact was baked at preset version {} but \
                     `{PRESETS_DIR}/{}.json` is only version {} — the tree's preset config is older than an artifact \
                     built from it, so the catalog cannot describe that artifact's styling. Update the preset config \
                     in the tree, or re-bake the region.",
                    a.region_id, a.preset_id, a.preset_version, a.preset_id, current.version
                ));
            }
            // Artifact older: a lagging partial re-bake. Deliberately NOT fatal. Unlike
            // an OBCM bump the artifact is perfectly readable — it is styled the way the
            // preset looked last month — so refusing to publish would turn a cosmetic lag
            // into total unavailability for every region not yet re-baked, and make a
            // ~20 CPU-hour full bake a precondition for any publish. The manifest states
            // the lag truthfully instead; §3 defines what a consumer may conclude. B1
            // owns whether a lag blocks a given publish: that is policy, and it gets
            // this list.
            std::cmp::Ordering::Less => warnings.push(format!(
                "region `{}` preset `{}`: artifact was baked at preset version {}, but the tree's preset is now \
                 version {} — it carries older styling until re-baked",
                a.region_id, a.preset_id, a.preset_version, current.version
            )),
            std::cmp::Ordering::Equal => {}
        }
    }

    // Coverage holes are legitimate (a bake can be partial) but never silent: a
    // region that quietly failed for one preset reads to a user as a curation choice.
    let mut by_region: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for a in artifacts {
        by_region.entry(a.region_id.as_str()).or_default().push(a.preset_id.as_str());
    }
    for (region, built) in &by_region {
        let missing: Vec<&str> = presets.keys().map(String::as_str).filter(|p| !built.contains(p)).collect();
        if !missing.is_empty() {
            warnings.push(format!("region `{region}` is missing preset(s): {}", missing.join(", ")));
        }
    }
    Ok(warnings)
}

// --- artifact inspection -----------------------------------------------------------------

struct ObcmHeader {
    version: u8,
    bbox: CoverageBBox,
}

/// Read the OBCM version and coverage bbox out of the artifact's own 40-byte header.
///
/// The whole point of the manifest's version field is that it describes the bytes that
/// will be downloaded, so it is read from those bytes. The layout is `OBCM_Spec.md` §1
/// (magic, version, then the bbox stored **lat, lon, lat, lon**).
fn read_obcm_header(path: &Path) -> Result<ObcmHeader, String> {
    let mut f = File::open(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut h = [0u8; HEADER_LEN];
    f.read_exact(&mut h).map_err(|e| {
        format!("{}: {e} — too short to be an OBCM artifact ({HEADER_LEN}-byte header)", path.display())
    })?;
    if h[..4] != MAGIC {
        return Err(format!("{}: not an OBCM file (bad magic)", path.display()));
    }
    let bbox = CoverageBBox {
        min_lat: rd_i32(&h, 5),
        min_lon: rd_i32(&h, 9),
        max_lat: rd_i32(&h, 13),
        max_lon: rd_i32(&h, 17),
    };
    if bbox.min_lat > bbox.max_lat || bbox.min_lon > bbox.max_lon {
        return Err(format!("{}: header bbox is inverted ({bbox:?})", path.display()));
    }
    if bbox.min_lat < -90_000_000
        || bbox.max_lat > 90_000_000
        || bbox.min_lon < -180_000_000
        || bbox.max_lon > 180_000_000
    {
        return Err(format!("{}: header bbox is outside the world ({bbox:?})", path.display()));
    }
    Ok(ObcmHeader { version: h[4], bbox })
}

/// Stream the file, returning `(bytes, lowercase hex sha256)`.
///
/// Streamed because artifacts are hundreds of megabytes; the byte count comes from the
/// stream rather than the directory entry, and is cross-checked against it, so a file
/// rewritten mid-hash fails loudly instead of publishing a hash for bytes that no
/// longer exist.
fn hash_file(path: &Path) -> Result<(u64, String), String> {
    let mut f = File::open(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let declared = f.metadata().map_err(|e| format!("{}: {e}", path.display()))?.len();
    let mut hasher = Sha256::new();
    let mut buf = vec![0u8; HASH_BUF];
    let mut total = 0u64;
    loop {
        let n = f.read(&mut buf).map_err(|e| format!("{}: {e}", path.display()))?;
        if n == 0 {
            break;
        }
        hasher.update(&buf[..n]);
        total += n as u64;
    }
    if total != declared {
        return Err(format!(
            "{}: changed while being hashed ({declared} bytes declared, {total} read)",
            path.display()
        ));
    }
    Ok((total, hex(&hasher.finalize())))
}

fn hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        use std::fmt::Write;
        let _ = write!(s, "{b:02x}");
    }
    s
}

