    /// The manifest a real tree produces must actually validate against the schema
    /// consumers will validate with — not merely be structurally plausible.
    #[test]
    fn generated_manifests_validate_against_the_checked_in_schema() {
        let schema: Value = serde_json::from_str(CATALOG_SCHEMA_JSON).expect("schema JSON");
        let compiled = boon::Compiler::new();
        let mut schemas = boon::Schemas::new();
        let mut compiler = compiled;
        compiler.add_resource("catalog.schema.json", schema).expect("add schema");
        let sid = compiler.compile("catalog.schema.json", &mut schemas).expect("compile schema");

        let t = TempTree::new("validate");
        example_tree(t.path());
        let instance: Value = serde_json::from_str(&manifest_json(&generated(t.path()).manifest)).unwrap();
        if let Err(e) = schemas.validate(&instance, sid) {
            panic!("generated manifest does not validate:\n{e:#}");
        }

        // The checked-in example is the artifact C1 will build against; validate it too.
        let example: Value = serde_json::from_str(CATALOG_EXAMPLE_JSON).unwrap();
        if let Err(e) = schemas.validate(&example, sid) {
            panic!("catalog.example.json does not validate:\n{e:#}");
        }

        // And the schema has teeth: a bad sha256 must be caught, not shrugged off.
        let mut broken = instance.clone();
        broken["artifacts"][0]["sha256"] = Value::from("NOTAHASH");
        assert!(schemas.validate(&broken, sid).is_err(), "the sha256 pattern must reject a non-hex digest");
        let mut future = instance;
        future["schema_version"] = Value::from(2);
        assert!(schemas.validate(&future, sid).is_err(), "a future envelope version must not validate as v1");
    }

    /// A truncated manifest cannot be half-consumed: JSON is self-delimiting, so every
    /// prefix of a valid document fails to parse. This is the format half of the
    /// "never partially consumed" rule; `write_atomic` is the writer half.
    #[test]
    fn every_truncation_of_a_manifest_fails_to_parse() {
        let t = TempTree::new("truncate");
        example_tree(t.path());
        let body = manifest_json(&generated(t.path()).manifest);
        assert!(serde_json::from_str::<CatalogManifest>(&body).is_ok());
        for cut in (1..body.len()).step_by(7) {
            assert!(
                serde_json::from_str::<CatalogManifest>(&body[..cut]).is_err(),
                "a manifest truncated at byte {cut} must not parse"
            );
        }
    }

