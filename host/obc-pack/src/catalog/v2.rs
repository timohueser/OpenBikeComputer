// --- the grid (OBCA_Spec.md §1) -----------------------------------------------------------

/// `GRID_ORIGIN`: the shared origin of every band and every cell size, on both axes
/// (`OBCA_Spec.md` §1.1). `−2^28` rather than `−90 000 000` because it is divisible
/// by every permitted cell size, which is what makes quadtree midpoints and cell
/// boundaries coincide.
pub const GRID_ORIGIN_UDEG: i32 = -268_435_456;

/// `WORLD_SIDE`: `2^29` µdeg. The world box (≈ ±268°) is deliberately wider than the
/// geographic domain, so a cell may overhang ±90°/±180° and MUST NOT be clamped.
pub const WORLD_SIDE_UDEG: i32 = 536_870_912;

/// Smallest permitted `log2(S)` (`OBCA_Spec.md` §1.1).
pub const MIN_CELL_LOG2: u8 = 10;

/// Largest permitted `log2(S)`.
pub const MAX_CELL_LOG2: u8 = 28;

/// A cell's identity: its size as `log2(µdeg)` and its row/column on the global grid.
///
/// The id is the coverage statement — `square` derives the cell's box from it in
/// exact integer arithmetic — which is why a catalog cell entry has no bbox and this
/// generator checks the artifact's header against the id instead (§11.6).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct CellId {
    pub log2: u8,
    pub i: u32,
    pub j: u32,
}

/// A cell's grid square, in microdegrees: `[min, min + S)` on both axes. Half-open,
/// with `max` the exclusive upper bound the OBCM header stores.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CellSquare {
    pub min_lat: i32,
    pub min_lon: i32,
    pub max_lat: i32,
    pub max_lon: i32,
}

impl CellId {
    /// Parse the canonical `<log2>/<i>/<j>` id (`OBCA_Spec.md` §1.3).
    ///
    /// Strict about the zero padding: producers MUST widen rather than truncate, so
    /// `18/1204/52` and `18/01204/1052` are *different strings for the same cell* and
    /// exactly the kind of ambiguity a content-addressed store must not have.
    pub fn parse(s: &str) -> Result<CellId, String> {
        let mut parts = s.split('/');
        let (Some(log2), Some(i), Some(j), None) = (parts.next(), parts.next(), parts.next(), parts.next()) else {
            return Err(format!("cell id `{s}` is not `<log2>/<i>/<j>`"));
        };
        if log2.is_empty() || log2.len() > 2 || !log2.bytes().all(|b| b.is_ascii_digit()) {
            return Err(format!("cell id `{s}`: `{log2}` is not a 1–2 digit cell size"));
        }
        let log2: u8 = log2.parse().map_err(|_| format!("cell id `{s}`: bad cell size"))?;
        if !(MIN_CELL_LOG2..=MAX_CELL_LOG2).contains(&log2) {
            return Err(format!(
                "cell id `{s}`: cell size 2^{log2} µdeg is outside 2^{MIN_CELL_LOG2}..=2^{MAX_CELL_LOG2}"
            ));
        }
        let width = Self::index_width(log2);
        let count = Self::grid_side(log2);
        let mut idx = [0u32; 2];
        for (slot, (text, axis)) in idx.iter_mut().zip([(i, "i"), (j, "j")]) {
            if text.len() != width || !text.bytes().all(|b| b.is_ascii_digit()) {
                return Err(format!("cell id `{s}`: `{axis}` must be {width} digits, zero-padded (got `{text}`)"));
            }
            let v: u32 = text.parse().map_err(|_| format!("cell id `{s}`: `{text}` is not a number"))?;
            if v >= count {
                return Err(format!("cell id `{s}`: `{axis}` = {v} is off the grid (0..{count})"));
            }
            *slot = v;
        }
        Ok(CellId { log2, i: idx[0], j: idx[1] })
    }

    /// Cells per axis at this size: `WORLD_SIDE / S`.
    pub fn grid_side(log2: u8) -> u32 {
        (WORLD_SIDE_UDEG as u32) >> log2
    }

    /// Zero-padding width: `max(4, decimal_width(WORLD_SIDE / S − 1))`
    /// (`OBCA_Spec.md` §1.3).
    pub fn index_width(log2: u8) -> usize {
        let last = Self::grid_side(log2) - 1;
        let digits = last.to_string().len();
        digits.max(4)
    }

    /// The half-open square this id names, in exact integer microdegrees. May
    /// overhang the geographic domain (`OBCA_Spec.md` §1.4) — that is legal and the
    /// box MUST NOT be clamped.
    pub fn square(&self) -> CellSquare {
        let side = 1i64 << self.log2;
        let min_lat = i64::from(GRID_ORIGIN_UDEG) + i64::from(self.i) * side;
        let min_lon = i64::from(GRID_ORIGIN_UDEG) + i64::from(self.j) * side;
        CellSquare {
            min_lat: min_lat as i32,
            min_lon: min_lon as i32,
            max_lat: (min_lat + side) as i32,
            max_lon: (min_lon + side) as i32,
        }
    }
}

impl fmt::Display for CellId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let w = CellId::index_width(self.log2);
        write!(f, "{}/{:0w$}/{:0w$}", self.log2, self.i, self.j, w = w)
    }
}

// --- the root document (§11.2) ------------------------------------------------------------

/// The v2 root: small, short-cached, and the only document a consumer reads before it
/// knows what the catalog offers.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct CatalogV2 {
    /// Envelope version, `2`. Checked before any other field.
    pub schema_version: u32,
    /// When this root was generated, RFC 3339 UTC — the only wall clock on the
    /// generation path (`OBCC_Spec.md` §5).
    pub generated_at: String,
    /// The catalog's **single** schema. Not an array: the hosted store carries the
    /// 7-LOD bikepacking ladder and nothing else, because a second schema would make
    /// the whole planet-shaped cell store exist twice (§11.2, epic #1016 D2).
    pub schema: SchemaEntry,
    /// Every skin offered, sorted by `id`. Inlined rather than referenced: one is
    /// ≈ 2 KB and a builder needs all of them at once to draw a picker.
    pub skins: Vec<SkinEntry>,
    /// Named selections, sorted by `id`.
    pub regions: Vec<RegionEntry>,
    /// One entry per band, sorted by `cell_log2` descending (§11.6).
    pub cell_index: Vec<CellIndexRef>,
    /// Legacy whole-region artifacts during migration (§11.9), with exactly v1 §3
    /// semantics. A v2 consumer MAY ignore it; a finished migration omits it. This
    /// generator never emits it — a v2 tree has no whole-region artifacts to
    /// describe — but the field is here because a consumer built on these types must
    /// be able to read a bakery that is still serving both.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub artifacts: Option<Vec<super::ArtifactEntry>>,
}

/// The schema: the identity of the cell store. Everything a consumer needs to price a
/// selection and an assembler needs to stamp a skin, with no out-of-band constant
/// (§11.3).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct SchemaEntry {
    /// Stable id, e.g. `bikepacking`.
    pub id: String,
    /// Monotone content revision. Every cell states the revision it was baked at, and
    /// a bump invalidates the whole store — assembly copies chunk bytes between files,
    /// which is only meaningful within one revision (`OBCA_Spec.md` §6.3).
    pub revision: u32,
    pub name: String,
    pub description: String,
    /// OBCM format version, read from the **cells' own headers**; every cell agrees or
    /// generation fails (§11.9).
    pub obcm_version: u8,
    /// The grid's constants, restated so no consumer hard-codes them.
    pub grid: GridEntry,
    /// The LOD ladder, coarsest first.
    pub lods: Vec<LodEntry>,
    /// The band table: which LODs and which non-geometry sections live in which cell
    /// size, and which file of a volume set they assemble into.
    pub bands: Vec<BandEntry>,
    /// The canonical style-id assignment. `obc-pack` numbers feature types 1-based in
    /// config document order and every feature header in every chunk references those
    /// ids, so the assignment is part of the cells' bytes — schema data, never skin
    /// data (§11.3).
    pub styles: Vec<StyleAssignment>,
    /// Routing facts baked into the cells. The island-prune threshold is schema data:
    /// two cells pruned at different thresholds do not assemble into a graph with
    /// consistent semantics (`OBCA_Spec.md` §3.5).
    pub routing: RoutingEntry,
    /// The per-LOD chunk capacity bound the cells were written with (`OBCM_Spec.md`
    /// §3). An assembler re-checks every copied offset pair against it.
    pub chunk_size: u32,
}

/// `OBCA_Spec.md` §1.1's constants. Published so a consumer computing a cell's square
/// or an assembly bbox never hard-codes a power of two.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct GridEntry {
    /// `−2^28` µdeg, on both axes.
    pub origin_udeg: i32,
    /// `2^29` µdeg: the world box's side.
    pub world_side_udeg: i32,
}

/// One rung of the LOD ladder.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct LodEntry {
    /// Ladder index, `0` = coarsest.
    pub index: u32,
    /// Meters-per-pixel upper bound; `null` for the `+inf` coarsest level
    /// (`OBCM_Spec.md` §3).
    pub max_mpp: Option<f64>,
    /// The band whose cells carry this LOD.
    pub band: String,
}

/// Which file of a volume set a band's content assembles into
/// (`OBCA_Spec.md` §5.1).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum BandRole {
    /// The one unsplittable file: nav graph, POIs, style table. Carries no LOD,
    /// because its headroom under `4 GiB − 1` is the design's hard limit.
    Core,
    /// The single whole-assembly coarse shard that keeps a zoomed-out viewport a
    /// one-file read.
    Coarse,
    /// An ordinary geometry shard's content; splits by bbox as needed.
    Geometry,
}

/// A non-geometry OBCM section a band may carry.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum BandSection {
    /// The navigation graph (`OBCM_Spec.md` §8).
    Nav,
    /// POIs and the hours pool (`OBCM_Spec.md` §7).
    Poi,
}

/// One band: a cell size plus the content its cells carry.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct BandEntry {
    /// Stable band id, e.g. `fine`. Also the band's segment in a cell URL.
    pub id: String,
    /// `log2(S)` in µdeg.
    pub cell_log2: u8,
    /// Ladder LODs this band's cells carry, ascending. Empty for the `core` band.
    pub lods: Vec<u32>,
    /// Non-geometry sections this band's cells carry. Only the `core` band has any.
    pub sections: Vec<BandSection>,
    /// Which file of a volume set this band becomes.
    pub role: BandRole,
}

/// One feature type's canonical style id — the assignment baked into every chunk.
